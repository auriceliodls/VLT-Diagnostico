// Utility helper to match search query
function compMatchQuery(comp: AtlasComponent, q: string): boolean {
  if (q.trim() === '') return true;
  const search = q.toLowerCase();
  return comp.label.toLowerCase().includes(search) ||
    comp.namePt.toLowerCase().includes(search) ||
    comp.nameEn.toLowerCase().includes(search) ||
    comp.id.toLowerCase().includes(search) ||
    comp.categoryPt.toLowerCase().includes(search) ||
    comp.categoryEn.toLowerCase().includes(search);
}
